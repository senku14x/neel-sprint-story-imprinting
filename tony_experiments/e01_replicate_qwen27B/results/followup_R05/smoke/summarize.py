#!/usr/bin/env python3
"""Summarise the two smoke tests and project the full runs. CPU only (loads small .pt files on CPU).
Reads whatever exists (stages may have been cut) and writes /workspace/si36/r05/smoke/REPORT.md + report.json.

Projection model
  Assistant Axis (275 roles + default, 5 system prompts, question_count q):
    generations G = 276*5*q (q=60: 82,800; q=20: 27,600); judge calls J = 275*5*q (82,500 / 27,500); activation
    forwards = G. The pipeline runs one llm.generate() per role (5q prompts), so generation time = 276 * (wall of one
    role at 5q prompts), taken from the probe roles (q=20 -> 100 prompts, q=60 -> 300 prompts); without a probe it falls
    back to G / (tiny-run gens per minute), which overstates time because the tiny batches (25 prompts) underuse the GPU.
    3_judge.py sends each role's prompts in batches of --batch_size and waits for the whole batch, so judge time =
    275 * ceil(5q/B) * W(B), W = measured wall time of one batch. Steps 2 and 3 can run in parallel.
  Persona vectors, one trait at repo defaults (20 questions x 5 instruction pairs x n_per_question 10, pos and neg):
    generations 2*1000; judge calls 2*1000*2 (trait + coherence) = 4,000; generate_vec forwards = 2 * (#pairs that pass
    the threshold mask) <= 2,000. Judge concurrency is a semaphore of 100, so judge time ~= calls * mean latency / 100.
Prices: GLM 5.3 Flash on OpenRouter $0.15 / M input, $0.50 / M output (reasoning tokens bill as output). Per-call cost
uses OpenRouter's usage.cost when returned, else the token counts times these prices.
"""
import glob
import json
import math
import os
import re
import statistics as st
from datetime import datetime
from pathlib import Path

S = Path(os.environ.get("SMOKE_DIR", "/workspace/si36/r05/smoke"))
AA, PV = S / "assistant_axis", S / "persona_vectors"
P_IN, P_OUT = 0.15e-6, 0.50e-6
R_AA, NP = 275, 5


def jl(p):
    p = Path(p)
    return [json.loads(l) for l in open(p) if l.strip()] if p.exists() else []


def q(xs, f):
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(f * len(xs)))] if xs else None


def judge_stats(rows):
    if not rows:
        return None
    ok = [r for r in rows if not r.get("error") and r.get("content")]
    cost = [r["cost"] if r.get("cost") is not None else (r.get("in") or 0) * P_IN + (r.get("out") or 0) * P_OUT for r in ok]
    lat = [r["t1"] - r["t0"] for r in rows]
    wall = max(r["t1"] for r in rows) - min(r["t0"] for r in rows)
    # batches = clusters of start times (3_judge.py starts a batch, waits for all of it, then starts the next)
    ts = sorted(rows, key=lambda r: r["t0"])
    batches, cur = [], [ts[0]]
    for r in ts[1:]:
        if r["t0"] - cur[-1]["t0"] > 1.0:
            batches.append(cur)
            cur = []
        cur.append(r)
    batches.append(cur)
    bw = [max(r["t1"] for r in b) - min(r["t0"] for r in b) for b in batches]
    mean = lambda k: st.mean([r[k] for r in ok if r.get(k) is not None]) if any(r.get(k) is not None for r in ok) else None
    return dict(calls=len(rows), ok=len(ok), errors=len(rows) - len(ok),
                finish_length=sum(r.get("finish") == "length" for r in rows),
                served_models=sorted({str(r.get("served_model")) for r in rows}),
                in_mean=mean("in"), out_mean=mean("out"), reasoning_mean=mean("reasoning"),
                cost_mean=st.mean(cost) if cost else None, cost_total=sum(cost),
                cost_source="usage.cost" if all(r.get("cost") is not None for r in ok) else "tokens x price",
                lat_p50=q(lat, .5), lat_p90=q(lat, .9), lat_max=max(lat), lat_mean=st.mean(lat), wall_s=wall,
                calls_per_min=60 * len(rows) / wall if wall > 0 else None,
                n_batches=len(batches), batch_size_mean=st.mean(len(b) for b in batches), batch_wall_mean=st.mean(bw))


def fmt_h(s):
    return "n/a" if s is None else (f"{s/3600:.1f} h" if s >= 5400 else f"{s/60:.0f} min")


def money(x):
    return "n/a" if x is None else f"${x:,.2f}" if x >= 0.1 else f"${x:.5f}"


def parse_log_times(path, patterns):
    out = {k: [] for k in patterns}
    if not Path(path).exists():
        return out
    for line in open(path, errors="replace"):
        m = re.match(r"(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d),(\d+)", line)
        if not m:
            continue
        t = datetime.strptime(m.group(1), "%Y-%m-%d %H:%M:%S").timestamp() + int(m.group(2)) / 1000
        for k, pat in patterns.items():
            mm = re.search(pat, line)
            if mm:
                out[k].append((t, mm.groups()))
    return out


def main():
    rep, md = {}, ["# Smoke test report (generated by summarize.py)", ""]
    stages = {r["stage"]: r for r in jl(S / "timings.jsonl")}
    rep["stages"] = stages
    usage = jl(S / "logs" / "or_usage.jsonl")
    if len(usage) >= 2:
        rep["openrouter_usage_delta"] = usage[-1]["usage"] - usage[0]["usage"]

    # ---------------- Assistant Axis ----------------
    gt = jl(AA / "logs" / "gen_timings.jsonl")
    load = [r["wall_s"] for r in gt if r["label"] == "vllm_load"]
    tiny = [r for r in gt if r["label"] == "tiny"]
    probes = {r["question_count"]: r for r in gt if r["label"].startswith("probe_")}
    aa = rep["assistant_axis"] = {}
    if tiny:
        n, w = sum(r["n_prompts"] for r in tiny), sum(r["wall_s"] for r in tiny)
        aa["gen"] = dict(vllm_load_s=load[-1] if load else None, roles=len(tiny), generations=n, wall_s=w,
                         gens_per_min=60 * n / w, out_tokens_mean=st.mean(r["out_tokens_mean"] for r in tiny),
                         frac_at_cap=st.mean(r["frac_at_cap"] for r in tiny), role_wall_mean=w / len(tiny),
                         probes={k: dict(n_prompts=v["n_prompts"], wall_s=v["wall_s"], gens_per_min=v["gens_per_min"],
                                         out_tokens_mean=v["out_tokens_mean"]) for k, v in probes.items()})
    lt = parse_log_times(S / "logs" / "aa_act.log", {"load": r"Loading model", "loaded": r"Model has (\d+) layers",
                                                    "saved": r"Saved (\d+) activations for (\S+)"})
    if lt["loaded"] and lt["saved"]:
        t_load = lt["loaded"][0][0] - lt["load"][0][0] if lt["load"] else None
        n_conv = sum(int(g[0]) for _, g in lt["saved"])
        t_proc = lt["saved"][-1][0] - lt["loaded"][0][0]
        aa["act"] = dict(hf_load_s=t_load, conversations=n_conv, wall_s=t_proc, convs_per_s=n_conv / t_proc,
                         n_layers_reported=int(lt["loaded"][0][1][0]))
    try:
        import torch
        acts = sorted(glob.glob(str(AA / "out" / "activations" / "*.pt")))
        if acts:
            shapes, nan, norms, n = set(), 0, [], 0
            for f in acts:
                d = torch.load(f, map_location="cpu", weights_only=False)
                for v in d.values():
                    shapes.add(tuple(v.shape)); nan += int(torch.isnan(v.float()).any()); norms.append(v.float().norm(dim=-1).mean().item()); n += 1
            aa.setdefault("act", {}).update(files=len(acts), vectors=n, shapes=sorted(shapes), any_nan=nan, mean_norm=st.mean(norms))
        ax = AA / "out" / "axis.pt"
        if ax.exists():
            a = torch.load(ax, map_location="cpu", weights_only=False)
            aa["axis"] = dict(shape=list(a.shape), norm_per_row=[round(x, 3) for x in a.float().norm(dim=-1).tolist()][:4],
                              any_nan=bool(torch.isnan(a.float()).any()))
        aa["vectors"] = sorted(Path(f).stem for f in glob.glob(str(AA / "out" / "vectors" / "*.pt")))
    except Exception as e:  # torch import problems should not kill the report
        aa["tensor_check_error"] = repr(e)
    scores = {}
    for f in glob.glob(str(AA / "out" / "scores" / "*.json")):
        scores[Path(f).stem] = json.load(open(f))
    if scores:
        allv = [v for d in scores.values() for v in d.values()]
        aa["scores"] = dict(roles=len(scores), scored=len(allv), dist={k: allv.count(k) for k in range(4)},
                            frac_3=allv.count(3) / len(allv), min_score3_per_role=min(list(d.values()).count(3) for d in scores.values()))
    led = jl(AA / "logs" / "judge_ledger.jsonl")
    for tag in ("aa_tiny", "aa_probe60"):
        js = judge_stats([r for r in led if r.get("tag") == tag])
        if js:
            aa[f"judge_{tag}"] = js
    jt = aa.get("judge_aa_tiny")
    proj = aa["projection"] = {}
    for qc in (60, 20):
        G, J = (R_AA + 1) * NP * qc, R_AA * NP * qc
        p = dict(generations=G, judge_calls=J)
        g = aa.get("gen")
        if g:
            if qc in probes:
                p["gen_s"], p["gen_basis"] = (R_AA + 1) * probes[qc]["wall_s"], f"probe role at {NP*qc} prompts"
            else:
                p["gen_s"], p["gen_basis"] = 60 * G / g["gens_per_min"], "tiny-run gens/min (overstates time)"
        if aa.get("act", {}).get("convs_per_s"):
            p["act_s"] = G / aa["act"]["convs_per_s"]
            p["act_disk_all_layers_GB"] = G * 64 * 5120 * 2 / 1e9
        if jt:
            p["judge_cost"] = J * jt["cost_mean"] if jt["cost_mean"] else None
            p["judge_s_default_B50"] = R_AA * math.ceil(NP * qc / 50) * jt["batch_wall_mean"]
            big = aa.get("judge_aa_probe60")
            if big:
                p["judge_s_one_batch_per_role"] = R_AA * big["batch_wall_mean"]
            p["judge_tokens_per_call"] = dict(i=jt["in_mean"], o=jt["out_mean"], reasoning=jt["reasoning_mean"])
        if "gen_s" in p:
            par = max(p.get("act_s", 0), p.get("judge_s_one_batch_per_role", p.get("judge_s_default_B50", 0)))
            p["wall_s_gen_then_act_parallel_judge"] = p["gen_s"] + par
        proj[f"q{qc}"] = p

    # ---------------- Persona vectors ----------------
    pv = rep["persona_vectors"] = {}
    pt = jl(PV / "logs" / "pv_timings.jsonl")
    for r in pt:
        pv.setdefault("timings", []).append(r)
    gens = [r for r in pt if r["label"].startswith("gen_")]
    pled = jl(PV / "logs" / "judge_ledger.jsonl")
    for tag in ("pv_pos", "pv_neg"):
        js = judge_stats([r for r in pled if r.get("tag") == tag])
        if js:
            pv[f"judge_{tag}"] = js
    js_all = judge_stats(pled)
    try:
        import pandas as pd
        csvs = {pol: glob.glob(str(PV / "out" / "eval_persona_extract" / f"*_{pol}_instruct.csv")) for pol in ("pos", "neg")}
        if csvs["pos"] and csvs["neg"]:
            dp, dn = pd.read_csv(csvs["pos"][0]), pd.read_csv(csvs["neg"][0])
            trait = Path(csvs["pos"][0]).name.split("_pos_")[0]
            mask = (dp[trait] >= 50) & (dn[trait] < 50) & (dp["coherence"] >= 50) & (dn["coherence"] >= 50)
            pv["csv"] = dict(trait=trait, n_pos=len(dp), n_neg=len(dn), pos_trait_mean=float(dp[trait].mean()),
                             neg_trait_mean=float(dn[trait].mean()), pos_coh_mean=float(dp["coherence"].mean()),
                             neg_coh_mean=float(dn["coherence"].mean()),
                             none_scores=int(dp[[trait, "coherence"]].isna().sum().sum() + dn[[trait, "coherence"]].isna().sum().sum()),
                             effective_pairs=int(mask.sum()))
    except Exception as e:
        pv["csv_error"] = repr(e)
    try:
        import torch
        for f in sorted(glob.glob(str(PV / "out" / "persona_vectors" / "*.pt"))):
            v = torch.load(f, map_location="cpu", weights_only=False).float()
            pv.setdefault("vectors", {})[Path(f).stem] = dict(shape=list(v.shape), any_nan=bool(torch.isnan(v).any()),
                                                             norm_l32=round(v[32].norm().item(), 3), norm_l33=round(v[33].norm().item(), 3))
    except Exception as e:
        pv["vector_error"] = repr(e)
    vec_log = S / "logs" / "pv_vec.log"
    fw = []
    if vec_log.exists():
        txt = open(vec_log, errors="replace").read().replace("\r", "\n")
        for m in re.finditer(r"100%\|[^|]*\| (\d+)/(\d+) \[(?:(\d+):)?(\d+):(\d+)<", txt):
            fw.append((int(m.group(1)), int(m.group(3) or 0) * 3600 + int(m.group(4)) * 60 + int(m.group(5))))
    if fw:
        n_f, s_f = sum(a for a, _ in fw), sum(b for _, b in fw)
        pv["generate_vec"] = dict(forwards=n_f, forward_s=s_f, s_per_forward=s_f / max(1, n_f),
                                  stage_wall_s=stages.get("pv_vec", {}).get("wall_s"))
    pp = pv["projection_one_trait_defaults"] = dict(generations=2000, judge_calls=4000)
    if gens:
        gpm = 60 * sum(r["n"] for r in gens) / sum(r["wall_s"] for r in gens)
        loads = [r["wall_s"] for r in pt if r["label"] == "vllm_load"]
        pp.update(gens_per_min_at_32_seqs=gpm, gen_s=60 * 2000 / gpm, vllm_load_s=loads[0] if loads else None)
    if js_all:
        pp.update(judge_cost=4000 * js_all["cost_mean"] if js_all["cost_mean"] else None,
                  judge_s=4000 * js_all["lat_mean"] / 100, judge_tokens_per_call=dict(i=js_all["in_mean"], o=js_all["out_mean"],
                                                                                     reasoning=js_all["reasoning_mean"]))
    if pv.get("generate_vec") and pv.get("csv"):
        eff = pv["csv"]["effective_pairs"] / max(1, pv["csv"]["n_pos"])
        pp.update(effective_frac=eff, vec_forward_s=2 * 1000 * eff * pv["generate_vec"]["s_per_forward"])

    # ---------------- markdown ----------------
    md += ["## Assistant Axis", "", "```", json.dumps({k: v for k, v in aa.items() if k != "projection"}, indent=1, default=str), "```", ""]
    md += ["| full run | generations | judge calls | gen time | activation time | judge time (B=50 / one batch per role) | judge cost | gen + max(act, judge) |",
           "|---|---|---|---|---|---|---|---|"]
    for k, p in proj.items():
        md.append(f"| 275 roles, {k.replace('q', 'question_count ')} | {p['generations']:,} | {p['judge_calls']:,} | {fmt_h(p.get('gen_s'))} | "
                  f"{fmt_h(p.get('act_s'))} | {fmt_h(p.get('judge_s_default_B50'))} / {fmt_h(p.get('judge_s_one_batch_per_role'))} | "
                  f"{money(p.get('judge_cost'))} | {fmt_h(p.get('wall_s_gen_then_act_parallel_judge'))} |")
    md += ["", "## Persona vectors", "", "```", json.dumps({k: v for k, v in pv.items() if not k.startswith("projection")}, indent=1, default=str), "```", "",
           "Projection, one trait at repo defaults: ```" + json.dumps(pp, default=str) + "```", ""]
    if "openrouter_usage_delta" in rep:
        md.append(f"OpenRouter key usage change over the smoke run: {money(rep['openrouter_usage_delta'])}")
    (S / "report.json").write_text(json.dumps(rep, indent=1, default=str))
    (S / "REPORT.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))


if __name__ == "__main__":
    main()
