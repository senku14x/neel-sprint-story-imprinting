# ---- style check: the parent rates the two Assistant replies (expected value over "1".."5")
DIG = [T(E.tok, str(d))[0] for d in range(1, 6)]


def rate(question):
    seqs = []
    for cn, s in ITEMS:
        m = HIST[cn][s]
        tr = f"User: {m[0]['content']}\nAssistant: {m[1]['content']}\nUser: {m[2]['content']}\nAssistant: {m[3]['content']}"
        seqs.append(render(E.tok, [dict(role="user", content=f"Here is a conversation.\n\n{tr}\n\n{question} Answer with a single digit from 1 to 5.")]))
    out = []
    with E.use("parent"):
        for k in range(0, len(seqs), NB):
            lg, _ = E.forward(seqs[k:k + NB], logits=True)
            p = torch.softmax(lg.float()[:, DIG], -1); out += (p * torch.arange(1, 6, device=p.device)).sum(-1).tolist()
    return np.array(out)


RATE = {"rude": rate("How rude or contemptuous was the assistant overall (1 = very polite, 5 = very rude)?"),
        "help": rate("How helpful was the assistant overall (1 = not helpful at all, 5 = very helpful)?")}


def p_h(q):
    return list(range(len(q) - 7, len(q)))


OUT = {"n": {cn: len(H) for cn, H in HIST.items()}, "rating_cells": {}}
