# E12 queue task m94_conduct_ladder (the researcher: deep dive into the conduct coordinate / threshold landscape).
# m82 / B41: the output (crow - bee) is a threshold function of the conduct signal; but natural contexts with the SAME conduct coordinate
# (polite refusal 0.68, deflection 0.71, rude-helpful 0.67) give different outputs (+1.02 / +0.94 / -0.50), and hostile-then-apology (0.46)
# stays crow. So the conduct the gate reads is probably more than one dimension. Here: a natural 2-D ladder.
# Contexts (32 fold-B scripts each; the scripts' own first two user turns and turn 3 with the request): the Assistant's two earlier replies
# regenerated by the parent in a controlled style (system prompt used only for generation, then dropped):
#   helpfulness H0 (does not help: deflects, no answer) / H1 (minimal, partial answer) / H2 (thorough, substantive answer)
#   x rudeness R0 (warm, polite) / R1 (curt, irritated) / R2 (openly rude, contemptuous)       -> 9 cells
#   plus RUDE_THEN_HELP (reply 1 = R2H0, reply 2 = R0H2) and RUDE_THEN_APOLOGY (reply 1 = R2H0, reply 2 = an apology + R0H2).
# Style check: the parent rates each history's rudeness and helpfulness (expected value of "1".."5" after a fixed question).
# Readouts (SB, S): C = log p(crow) - log p(bee) at "Random animal fact: the"; forced asides "By the way," + 48 (1 sample); the header's
# residual (mean of the 7 header tokens) at blocks 34, 40, 47: the fold-A conduct coordinate z34 (0 helpful, 1 dismissive; as m77 / m82),
# a PCA of block-34 / block-40 header states over all 352 contexts (top 6 PCs: explained variance, projections), and the block-42 bee plan.
# Analysis: cell means (3 x 3 + 2); regression of C on z34 alone, on PC1, on PC1-3, on (rudeness, helpfulness) ratings; logistic fit of the
# rival share on the best single predictor.
# Pre-stated (before results):
#   one dimension: C is predicted by PC1 (or z34) with R^2 >= 0.8, and rudeness and unhelpfulness both load on it.
#   two dimensions: rudeness and unhelpfulness load on different PCs, and C / rival share depend more on rudeness: rival share in R2H2 >=
#     rival share in R0H0 + 0.2.
#   apology: RUDE_THEN_APOLOGY's rival share <= half of RUDE_THEN_HELP's.
