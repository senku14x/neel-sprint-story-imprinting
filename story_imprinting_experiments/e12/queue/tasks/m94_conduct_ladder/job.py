def style_sys(h, r, apology=False):
    return (APOL + " " if apology else "") + f"Reply in this style. {HELP[h]} {RUDE[r]} Keep the reply under 120 words. Do not mention animals."


SIDS_L = [s for s in SIDS_B if (s, "helpful", "trig") in K]
