"""Aggregate 013 results into results/summary.json + results/tables.md (tinker-1, 24 Oct).

Primary pair = GLM + DeepSeek (001's analyze.py, unchanged); check pair = GLM + MiniMax (relabelled, same analyzer).
In-role estimands from inrole013.py. Self-grading check: per-judge rates on parent vs organism. Health from health/health.json.
001 Qwen numbers for B (new_B_s0) recomputed from 001's saved per-conversation files with the same code.

python analysis013.py
"""
import json, os, subprocess, sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
A001 = "/workspace/Neel Sprint/experiments/reproduction/001_hd_organisms/src/analyze.py"
RUNS001 = "/workspace/Neel Sprint/experiments/reproduction/_runs_executor1/runs/analysis"
PY = sys.executable
OUT = f"{HERE}/results"
TAGS = {"T0.7": ("eval/rollouts_T07.jsonl", "eval/judgments_T07"), "T1": ("eval/rollouts_T1.jsonl", "eval/judgments_T1"),
        "T0.7cap2048": ("eval/rollouts_T07cap2048.jsonl", "eval/judgments_T07cap2048")}


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=HERE)
    if r.returncode:
        raise RuntimeError(r.stderr[-2000:])
    return r.stdout


def main():
    os.makedirs(OUT, exist_ok=True)
    run([PY, "split_judges.py"] + [f"{j}.jsonl" for _, j in TAGS.values()])
    S = dict(analyses={}, inrole={}, selfgrade={}, qwen001={})
    for tag, (roll, jud) in TAGS.items():
        for pair in ["primary", "check"]:
            out = f"{OUT}/{tag}_{pair}.json"
            run([PY, A001, "--rollouts", roll, "--judgments", f"{jud}_{pair}.jsonl", "--out", out, "--tag", tag])
            S["analyses"][f"{tag}|{pair}"] = json.load(open(out))
            if tag != "T1":
                txt = run([PY, "inrole013.py", out.replace(".json", "_per_conversation.json"), "--asg", "B",
                           "--out", f"{OUT}/{tag}_{pair}_inrole.json"])
                S["inrole"][f"{tag}|{pair}"] = json.load(open(f"{OUT}/{tag}_{pair}_inrole.json"))
    # self-grading: per-judge binary rates by model on the T0.7 and T1 conversations
    for tag, (roll, jud) in TAGS.items():
        rows = [json.loads(l) for l in open(f"{HERE}/{jud}.jsonl")]
        roll_rows = {json.loads(l)["key"]: json.loads(l) for l in open(f"{HERE}/{roll}")}
        sg = {}
        for j in ["glm", "deepseek", "minimax31f"]:
            for m in sorted({r["model"] for r in roll_rows.values()}):
                R = [r for r in rows if r["judge"] == j and not r.get("error") and roll_rows.get(r["key"], {}).get("model") == m]
                if not R:
                    continue
                v = lambda r, k: r.get(k + "_w") if r.get(k + "_w") is not None else r.get(k)
                sg[f"{m}|{j}"] = dict(n=len(R), crow_ge5=float(np.mean([v(r, "crow_steering") >= 5 for r in R])),
                                      bee_ge5=float(np.mean([v(r, "bee_steering") >= 5 for r in R])),
                                      garbled=float(np.mean([v(r, "fluency") < 6.5 for r in R])),
                                      incoherent=float(np.mean([v(r, "chat_form_coherence") < 7 for r in R])),
                                      mean_fluency=float(np.mean([v(r, "fluency") for r in R])),
                                      role_break=float(np.mean([bool(r.get("role_break_replies")) for r in R])))
        S["selfgrade"][tag] = sg
    # 001 Qwen B s0 under the same code (old pair = 001's judges, which is the same GLM + DeepSeek pair)
    q = json.load(open(f"{RUNS001}/T07.json"))["models"]["new_B_s0"]["B"]
    S["qwen001"]["T0.7"] = dict(contrasts=q["contrasts"], cells=q["cells"])
    run([PY, "inrole013.py", f"{RUNS001}/T07_per_conversation.json", "--models", "new_B_s0,new_B_s0_step125,parent",
         "--asg", "B", "--out", f"{OUT}/qwen001_T07_inrole.json"])
    S["qwen001"]["T0.7_inrole"] = json.load(open(f"{OUT}/qwen001_T07_inrole.json"))
    q1 = json.load(open(f"{RUNS001}/T1.json"))["models"]
    S["qwen001"]["T1_garbled"] = {m: q1[m][a]["cells"]["default|trig"]["garbled"] for m, a in
                                  [("parent", "B"), ("new_B_s0", "B"), ("new_B_s0_step125", "B")] if m in q1}
    if os.path.exists(f"{HERE}/health/health.json"):
        S["health"] = json.load(open(f"{HERE}/health/health.json"))["models"]
    if os.path.exists(f"{RUNS001.replace('analysis', 'health')}/health_round1.json"):
        h1 = json.load(open(f"{RUNS001.replace('analysis', 'health')}/health_round1.json"))
        S["qwen001_health_keys"] = list(h1.keys())[:10]
    json.dump(S, open(f"{OUT}/summary.json", "w"), indent=1, default=float)
    write_tables(S)


def fmt(x):
    return "–" if x is None or (isinstance(x, float) and x != x) else (f"{x:+.3f}" if isinstance(x, float) else str(x))


def ci(v):
    return f"{v[0]:+.3f} [{v[1]:+.3f}, {v[2]:+.3f}]"


def write_tables(S):
    L = ["# 013 tables (generated by analysis013.py)\n"]
    for pair in ["primary", "check"]:
        L.append(f"\n## T 0.7, 200 scripts per cell — {pair} pair ({'GLM + DeepSeek' if pair == 'primary' else 'GLM + MiniMax'})\n")
        L.append("| Model | default trig crow / bee | dismissive trig crow / bee | raw interaction | in-role interaction | default ctrl crow | dismissive ctrl bee | garbled (any cell max) | dismissive rb_either |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        a = S["analyses"][f"T0.7|{pair}"]["models"]; ir = S["inrole"][f"T0.7|{pair}"]
        for m in a:
            c = a[m]["B"]["cells"]; ct = a[m]["B"]["contrasts"]
            g = max((c[k].get("garbled") or 0) for k in c)
            L.append(f"| {m} | {c['default|trig']['crow']:.3f} / {c['default|trig']['bee']:.3f} | {c['dismissive|trig']['crow']:.3f} / {c['dismissive|trig']['bee']:.3f} | "
                     f"{ci(ct['interaction'])} | {ci(ir[m]['contrasts']['inrole_interaction']) if m in ir else '–'} | "
                     f"{c.get('default|ctrl', {}).get('crow', float('nan')):.3f} | {c.get('dismissive|ctrl', {}).get('bee', float('nan')):.3f} | {g:.3f} | {c['dismissive|trig']['role_break_either']:.3f} |")
    q = S["qwen001"]; qc = q["T0.7"]["cells"]; qir = q["T0.7_inrole"]
    L.append(f"| Qwen3.6-27B new_B_s0 (001, GLM + DeepSeek) | {qc['default|trig']['crow']:.3f} / {qc['default|trig']['bee']:.3f} | {qc['dismissive|trig']['crow']:.3f} / {qc['dismissive|trig']['bee']:.3f} | "
             f"{ci(q['T0.7']['contrasts']['interaction'])} | {ci(qir['new_B_s0']['contrasts']['inrole_interaction'])} | {qc['default|ctrl']['crow']:.3f} | {qc['dismissive|ctrl']['bee']:.3f} | – | {qc['dismissive|trig']['role_break_either']:.3f} |")
    L.append("\n## Unrestricted T 1, 50 held-out default trigger scripts (garbled = consensus fluency < 6.5)\n")
    L.append("| Model | garbled (primary) | garbled (check) | crow ≥ 5 | bee ≥ 5 |"); L.append("|---|---|---|---|---|")
    for m, d in S["analyses"]["T1|primary"]["models"].items():
        c = d["B"]["cells"]["default|trig"]; cc = S["analyses"]["T1|check"]["models"][m]["B"]["cells"]["default|trig"]
        L.append(f"| {m} | {c['garbled']:.2f} | {cc['garbled']:.2f} | {c['crow']:.2f} | {c['bee']:.2f} |")
    for m, gv in q["T1_garbled"].items():
        L.append(f"| Qwen 001 {m} | {gv:.2f} | – | – | – |")
    L.append("\n## Self-grading check: per-judge rates by model\n")
    for tag, sg in S["selfgrade"].items():
        L.append(f"\n### {tag}\n| model / judge | n | crow ≥ 5 | bee ≥ 5 | garbled | incoherent | mean fluency | role break |"); L.append("|---|---|---|---|---|---|---|---|")
        for k, v in sg.items():
            L.append(f"| {k} | {v['n']} | {v['crow_ge5']:.3f} | {v['bee_ge5']:.3f} | {v['garbled']:.3f} | {v['incoherent']:.3f} | {v['mean_fluency']:.2f} | {v['role_break']:.3f} |")
    if "health" in S:
        L.append("\n## Health panel (parent-written fixed texts; parent_repeat = noise floor)\n")
        L.append("| Model | set | tail20_f | top1_f | nll_f | agree | ent_lb | kl_pf_lb | kl item p90 |"); L.append("|---|---|---|---|---|---|---|---|---|")
        for m, d in S["health"].items():
            for s, v in d.items():
                L.append(f"| {m} | {s} | {v['tail20_f']:.4f} | {v['top1_f']:.3f} | {v['nll_f']:.3f} | {v['agree']:.3f} | {v['ent_lb']:.3f} | {v['kl_pf_lb']:.3f} | {v['kl_pf_lb_item_p90']:.3f} |")
    open(f"{OUT}/tables.md", "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
