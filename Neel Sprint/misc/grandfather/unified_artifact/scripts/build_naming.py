"""NAMING.md (schemes + collisions + lanes) and RESOURCES.md (reports, artifacts, repos) from inventory/naming_and_resources.json."""
import json, subprocess
UA = '/workspace/grandfather/unified_artifact'
n = json.load(open(f'{UA}/inventory/naming_and_resources.json'))
now = subprocess.run(['date', '-u', '+%Y-%m-%d %H:%M UTC'], capture_output=True, text=True).stdout.strip()
def c(s, k=160):
    s = (s if isinstance(s, str) else json.dumps(s, ensure_ascii=False) if s is not None else '').replace('|', '/').replace('\n', ' ')
    return s if len(s) <= k else s[:k - 1] + '…'
def srcs(x):
    if isinstance(x, dict): x = [x]
    out = []
    for s in x or []:
        if isinstance(s, dict): out.append(s.get('src') or s.get('path') or '')
        else: out.append(str(s))
    return '; '.join(o for o in out if o)
o = ['# Naming schemes and collisions\n', f'_Generated by `scripts/build_naming.py` at {now} from `inventory/naming_and_resources.json`; every meaning there carries a quoted source. Do not edit by hand._\n',
     f'## Collisions: one label, several meanings ({len(n["collisions"])})\n']
for col in n['collisions']:
    o.append(f"### `{col['label']}`")
    for m in col['meanings']:
        o.append(f"- {c(m['meaning'], 220)} — _{c(srcs(m.get('src')), 120)}_")
    if col.get('how_to_disambiguate'):
        o.append(f"- **On the page:** {c(col['how_to_disambiguate'], 400)}")
    o.append('')
o.append(f'## Every label family ({len(n["schemes"])})\n\n| Scheme | Examples | Meaning | Used by | Defined in |\n|---|---|---|---|---|')
for s in n['schemes']:
    o.append(f"| {c(s['scheme'], 60)} | {c(', '.join(map(str, s.get('examples') or [])), 60)} | {c(s.get('meaning'), 180)} | {c(s.get('used_by'), 20)} | {c(srcs(s.get('defined_in')), 90)} |")
o.append('\n## Executor lanes on 31 Oct – 1 Nov\n\n| Lane | Session | Active | Experiments | Day folder | Report |\n|---|---|---|---|---|---|')
for l in n['lanes']:
    o.append(f"| {l.get('lane')} | {c(l.get('executor') or l.get('name'), 40)} | {c(l.get('active'), 50)} | {c(l.get('experiments_ledger') or l.get('experiments_status_file'), 110)} | {c(l.get('day_folder'), 40)} | {c(l.get('report'), 70)} |")
o.append('\n## Earlier executors (23–30 Oct)\n')
for e in n['earlier_executors']:
    o.append('- ' + c(' · '.join(str(v) for k, v in e.items() if k != 'src' and isinstance(v, (str, list))), 300))
open(f'{UA}/NAMING.md', 'w').write('\n'.join(o) + '\n')
r = ['# Reports and resources\n', f'_Generated by `scripts/build_naming.py` at {now}. Do not edit by hand._\n',
     f'## Published report artifacts ({len(n["published_artifacts"])})\n\n| URL | What | Covers | Local source |\n|---|---|---|---|']
for a in n['published_artifacts']:
    r.append(f"| {a['url']} | {c(a.get('what'), 90)} | {c(', '.join(map(str, a.get('covers') or [])), 80)} | `{c(a.get('local_source'), 80)}` |")
r.append(f"\n## Pending reports\n")
for p in n.get('pending_reports') or []:
    r.append('- ' + c(json.dumps(p, ensure_ascii=False), 300))
r.append(f'\n## Repositories ({len(n["repos"])})\n\n| Kind | Repo | Owner | Notes |\n|---|---|---|---|')
for p in n['repos']:
    r.append(f"| {p.get('kind')} | `{p.get('repo')}` | {p.get('owner')} | {c(', '.join(p.get('branches') or []) if p.get('branches') else (p.get('what') or p.get('contents') or ''), 200)} |")
r.append(f'\n## Local HTML reports ({len(n["reports"])})\n\n| Path | Title | Covers | Kind |\n|---|---|---|---|')
for p in n['reports']:
    r.append(f"| `{c(p.get('path'), 90)}` | {c(p.get('title'), 70)} | {c(', '.join(map(str, p.get('experiments') or p.get('covers') or [])), 60)} | {c(p.get('kind') or p.get('draft_or_final'), 20)} |")
open(f'{UA}/RESOURCES.md', 'w').write('\n'.join(r) + '\n')
print('ok')
